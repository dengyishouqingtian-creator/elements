function simulateReply(profile, text) {
  const speech = classifySpeech(text);
  const el = profile.mainElement;
  let reply, templateId;
  if (el && REPLIES[el] && REPLIES[el][speech.id]) {
    const arr = REPLIES[el][speech.id];
    reply = arr[(text.length + profile.obsCount) % arr.length];
    templateId = 'SIM-' + el.toUpperCase() + '-' + speech.id.toUpperCase();
  } else {
    reply = NEUTRAL_REPLIES[speech.id];
    templateId = 'SIM-NEUTRAL-' + speech.id.toUpperCase();
  }
  let tier, confidence;
  if (!profile.obsCount) { tier = '暂无该人物记录，当前仅为通用情景演示'; confidence = '低'; }
  else if (!el) { tier = '目前没有明显主要线索，使用中性模板'; confidence = '低'; }
  else if (profile.obsCount < 5) { tier = '资料较少，暂不能形成稳定画像，回复仅供练习参考'; confidence = '中'; }
  else { tier = '根据当前观察线索生成模拟'; confidence = '高'; }
  const why = el ? WHY_STYLE[el] + (profile.secondary ? '；副倾向（' + profile.secondaryName + '）会让表达再带一点变通' : '') + '。' : '尚无足够记录判断他的主要倾向，先用中性沟通模板。';
  return { speech, reply, templateId, why, advice: SIM_ADVICE[speech.id], tier, confidence, evidenceCount: profile.evidenceCount || 0 };
}

